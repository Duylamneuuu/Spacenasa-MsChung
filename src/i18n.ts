import { useSyncExternalStore } from 'react';

export type Lang = 'en' | 'vi';
const STORE = 'apogee-lang';
function initial(): Lang {
  try {
    const q = new URLSearchParams(location.search).get('lang');
    if (q === 'vi' || q === 'en') return q;
    return localStorage.getItem(STORE) === 'vi' ? 'vi' : 'en';
  } catch { return 'en'; }
}
let current: Lang = initial();
const listeners = new Set<() => void>();
if (typeof document !== 'undefined') document.documentElement.lang = current === 'vi' ? 'vi' : 'en-US';
export function setLang(next: Lang) {
  current = next;
  try { localStorage.setItem(STORE, next); } catch { /* private mode */ }
  document.documentElement.lang = next === 'vi' ? 'vi' : 'en-US';
  listeners.forEach(f => f());
}
export const getLang = () => current;
export function useLang() {
  return useSyncExternalStore(cb => { listeners.add(cb); return () => { listeners.delete(cb); }; }, () => current, () => current);
}

